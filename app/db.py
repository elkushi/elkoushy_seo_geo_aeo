"""Storage for the web app: a local SQLite file (default) or Postgres when DATABASE_URL is set
(e.g. Neon's free tier - needed on hosts without a persistent disk, such as Render Free).

Report files (HTML, Markdown, PDF) are stored in the database too (table job_files), so nothing
depends on the local filesystem surviving a restart. Queries are written once with `?`
placeholders and portable SQL (ON CONFLICT ... DO NOTHING / DO UPDATE works in both).
"""

import sqlite3
import threading
from pathlib import Path

SCHEMA = [
    "CREATE TABLE IF NOT EXISTS users (id {pk}, email TEXT UNIQUE NOT NULL, created TEXT, last_login TEXT)",
    "CREATE TABLE IF NOT EXISTS login_tokens (hash TEXT PRIMARY KEY, email TEXT NOT NULL, expires TEXT, used INTEGER DEFAULT 0, created TEXT)",
    "CREATE TABLE IF NOT EXISTS sessions (hash TEXT PRIMARY KEY, user_id INTEGER NOT NULL, expires TEXT)",
    "CREATE TABLE IF NOT EXISTS jobs (id TEXT PRIMARY KEY, user_id INTEGER NOT NULL, url TEXT, domain TEXT, status TEXT, "
    "steps TEXT, created TEXT, finished TEXT, site TEXT, scores TEXT, counts TEXT, summary TEXT, skipped TEXT, error TEXT)",
    "CREATE INDEX IF NOT EXISTS jobs_user ON jobs(user_id, created)",
    "CREATE INDEX IF NOT EXISTS jobs_domain ON jobs(domain, created)",
    "CREATE TABLE IF NOT EXISTS job_files (job_id TEXT NOT NULL, name TEXT NOT NULL, content {blob}, PRIMARY KEY (job_id, name))",
]


class Database:
    def __init__(self, url: str | None, sqlite_path: Path):
        self.pg = bool(url)
        self.url, self.sqlite_path = url, sqlite_path
        self.lock = threading.Lock()
        self.conn = None
        self._connect()
        types = {"pk": "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", "blob": "BYTEA"} if self.pg else \
                {"pk": "INTEGER PRIMARY KEY", "blob": "BLOB"}
        for stmt in SCHEMA:
            self.q(stmt.format(**types))

    @property
    def kind(self) -> str:
        return "postgres" if self.pg else "sqlite"

    def _connect(self) -> None:
        if self.pg:
            import psycopg
            from psycopg.rows import dict_row
            self.conn = psycopg.connect(self.url, autocommit=True, row_factory=dict_row, connect_timeout=15)
        else:
            self.sqlite_path.parent.mkdir(parents=True, exist_ok=True)
            self.conn = sqlite3.connect(self.sqlite_path, check_same_thread=False)
            self.conn.row_factory = sqlite3.Row
            self.conn.execute("PRAGMA journal_mode=WAL")

    def _run(self, sql: str, args):
        if self.pg:
            cur = self.conn.execute(sql.replace("?", "%s"), args)
            return cur.fetchall() if cur.description else []
        cur = self.conn.execute(sql, args)
        self.conn.commit()
        return cur.fetchall()

    def q(self, sql: str, args=(), one=False):
        with self.lock:
            try:
                rows = self._run(sql, args)
            except Exception as e:
                # serverless Postgres (Neon) closes idle connections: reconnect once and retry
                if not (self.pg and type(e).__module__.startswith("psycopg")
                        and type(e).__name__ in ("OperationalError", "InterfaceError")):
                    raise
                self._connect()
                rows = self._run(sql, args)
        return (rows[0] if rows else None) if one else rows

    def put_file(self, job_id: str, name: str, content: bytes) -> None:
        self.q("INSERT INTO job_files (job_id, name, content) VALUES (?, ?, ?) "
               "ON CONFLICT (job_id, name) DO UPDATE SET content = excluded.content", (job_id, name, content))

    def get_file(self, job_id: str, name: str) -> bytes | None:
        row = self.q("SELECT content FROM job_files WHERE job_id = ? AND name = ?", (job_id, name), one=True)
        return bytes(row["content"]) if row and row["content"] is not None else None
